TERCEREX START	0H
	RESB	12
CICLO	+JSUB	ENTRADA
	BASE	ARREG
	LDB	#(ENTRADA+32)
VALOR	EQU	(CICLO-PRUEBA)*2
ARREG	RESW	20
	USE	DATOS
ETIQ1	RESB	15
DATO	EQU	*
MAYOR	WORD	(CICLO-ENTRADA)+DATO
MAX	EQU	MAYOR-ETIQ+10
	USE
PRUEBA LDA	#(MAX*2)
	+ADD	@ENTRADA,X
	JSUB	#(INICIO+12)
	USE	CODIGO
	TIXR	T
NUMERO EQU	(CICLO-ETIQ)*2
	WORD	CICLO-INICIO
INICIO LDA	#(MAYOR+DATO-15)
	USE	DATOS
CALC	EQU	((ENTRA-ETIQ)+6)/VALOR
ENTRADA BYTE X'3E0'
	END	INICIO